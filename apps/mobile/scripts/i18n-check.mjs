#!/usr/bin/env node
/**
 * i18n consistency check and type generation.
 *
 * Verifies that:
 *  1. every locale has exactly the same key set as the reference locale,
 *  2. no key is missing a translation (empty string),
 *  3. no key is unreferenced by the source code.
 *
 * With --write it regenerates lib/i18n/generated-keys.ts, the union type that
 * makes t() reject unknown keys at compile time.
 *
 * Usage:
 *   node scripts/i18n-check.mjs          # check only, non-zero exit on drift
 *   node scripts/i18n-check.mjs --write  # check + regenerate the key type
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const localesDir = path.join(root, 'lib/i18n/locales');
const REFERENCE = 'de';
const WRITE = process.argv.includes('--write');

/** Source directories scanned for key usage. */
const SOURCE_DIRS = ['app', 'components', 'lib', 'hooks', 'contexts'];

function flatten(obj, prefix = '', out = new Map()) {
  for (const [key, value] of Object.entries(obj)) {
    const full = prefix ? `${prefix}.${key}` : key;
    if (value && typeof value === 'object' && !Array.isArray(value)) {
      flatten(value, full, out);
    } else {
      out.set(full, value);
    }
  }
  return out;
}

function readLocale(locale) {
  const file = path.join(localesDir, `${locale}.json`);
  return flatten(JSON.parse(fs.readFileSync(file, 'utf8')));
}

function collectSources() {
  const files = [];
  for (const dir of SOURCE_DIRS) {
    const abs = path.join(root, dir);
    if (!fs.existsSync(abs)) continue;
    const stack = [abs];
    while (stack.length) {
      const current = stack.pop();
      for (const entry of fs.readdirSync(current, { withFileTypes: true })) {
        const full = path.join(current, entry.name);
        if (entry.isDirectory()) {
          if (entry.name === 'node_modules' || entry.name === 'locales') continue;
          stack.push(full);
        } else if (/\.tsx?$/.test(entry.name)) {
          files.push(full);
        }
      }
    }
  }
  return files.map(f => fs.readFileSync(f, 'utf8')).join('\n');
}

const locales = fs
  .readdirSync(localesDir)
  .filter(f => f.endsWith('.json'))
  .map(f => path.basename(f, '.json'))
  .sort();

const reference = readLocale(REFERENCE);
const source = collectSources();

// Keys referenced as a plain string literal anywhere in the source.
// Quoted strings alone are not enough: keys also appear inside template
// literals, e.g. `${t('vacation.form.currency')} (...)`, where the surrounding
// backticks would otherwise swallow the match.
const literals = new Set();
for (const match of source.matchAll(/['"`]([^'"`\n]+)['"`]/g)) {
  literals.add(match[1]);
}
// Second pass: any dotted identifier inside a t(...) call, regardless of the
// quote style or surrounding interpolation.
for (const match of source.matchAll(/\bt\(\s*['"`]([\w.]+)['"`]/g)) {
  literals.add(match[1]);
}
// Keys built dynamically, e.g. t(`checklist.categories.${category}`).
const dynamicPrefixes = [...source.matchAll(/`([\w.]+)\.\$\{/g)].map(m => m[1]);

const problems = [];

// 1 + 2: locale parity and empty values
for (const locale of locales) {
  const entries = readLocale(locale);

  if (locale !== REFERENCE) {
    const missing = [...reference.keys()].filter(k => !entries.has(k));
    const extra = [...entries.keys()].filter(k => !reference.has(k));
    for (const key of missing) problems.push(`${locale}: missing key  ${key}`);
    for (const key of extra) problems.push(`${locale}: unknown key  ${key}`);
  }

  for (const [key, value] of entries) {
    if (typeof value === 'string' && value.trim() === '') {
      problems.push(`${locale}: empty translation  ${key}`);
    }
  }
}

// 3: unreferenced keys
const unused = [...reference.keys()].filter(key => {
  if (literals.has(key)) return false;
  return !dynamicPrefixes.some(prefix => key.startsWith(`${prefix}.`));
});
for (const key of unused) problems.push(`unused key  ${key}`);

if (WRITE) {
  const keys = [...reference.keys()].sort();
  const body = `/**
 * Generated by scripts/i18n-check.mjs - do not edit by hand.
 * Run \`npm run i18n:write\` after changing lib/i18n/locales/${REFERENCE}.json.
 */

export type TranslationKey =
${keys.map(k => `  | '${k}'`).join('\n')};
`;
  fs.writeFileSync(path.join(root, 'lib/i18n/generated-keys.ts'), body);
  console.log(`Wrote lib/i18n/generated-keys.ts (${keys.length} keys)`);
}

console.log(`Locales: ${locales.join(', ')} | reference: ${REFERENCE} | keys: ${reference.size}`);

if (problems.length > 0) {
  console.error(`\n${problems.length} problem(s):`);
  for (const problem of problems) console.error(`  ${problem}`);
  process.exit(1);
}

console.log('i18n OK: locales in sync, no empty translations, no unused keys.');
